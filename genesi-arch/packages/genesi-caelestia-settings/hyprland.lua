-- Genesi OS — default Hyprland configuration for the "Hyprland + caelestia-shell"
-- desktop option, in the Lua format Hyprland reads since 0.55 (and ONLY reads
-- since 0.57, which dropped hyprland.conf). Shipped as /etc/skel; existing
-- users get it from the genesi-caelestia-settings migration. Edit freely.
--
-- This is the same desktop as the hyprland.conf next to it, line for line.
-- Both files are kept: Hyprland 0.54 and older read only the .conf, 0.55-0.56
-- prefer this file when it exists, 0.57+ read only this file.
--
-- Your own additions: put them in ~/.config/hypr/user.lua (loaded last, so it
-- wins). A Genesi upgrade never touches that file.
--
-- The caelestia shell (bar, launcher, notifications, OSDs, wallpaper) is
-- started below -- do NOT also run waybar/swaybg, caelestia owns the surface.

-- Loads ~/.config/hypr/<name>.lua when it exists. A missing file is normal
-- (nobody has changed a display setting yet); a BROKEN one is reported on
-- screen and the rest of the config still loads, instead of one bad line in a
-- drop-in leaving the whole desktop on Hyprland's autogenerated defaults.
local function optional(name)
    local ok, err = pcall(require, name)
    if not ok and not tostring(err):find("module '" .. name .. "' not found", 1, true) then
        hl.notification.create({ text = "Genesi: " .. name .. ".lua: " .. tostring(err), timeout = 10000 })
    end
end

