-- Autostart
---------------------------------------------------------------------------------
hl.on("hyprland.start", function()
    -- The bar. In a VM the GPU/EGL stack is unreliable and Quickshell crashes
    -- to a black screen, so force Qt Quick's software renderer there; on real
    -- hardware the branch is skipped. Which bar starts is a remembered choice
    -- (`genesi-bar shell` switches caelestia's rail / Genesi's top bar).
    hl.exec_cmd("sh -c 'if [ \"$(systemd-detect-virt)\" != none ]; then export QT_QUICK_BACKEND=software LIBGL_ALWAYS_SOFTWARE=1; fi; genesi-bar shell --start'")
    -- PolicyKit agent so GUI apps can ask for privileges.
    hl.exec_cmd("/usr/lib/polkit-kde-authentication-agent-1")
    -- Clipboard history.
    hl.exec_cmd("wl-paste --watch cliphist store")
    -- Genesi tray apps. Hyprland does not run /etc/xdg/autostart.
    hl.exec_cmd("genesi-update --tray")
    hl.exec_cmd("genesi-ai-tray")
    hl.exec_cmd("genesi-ai-quick --background")
    hl.exec_cmd("genesi-containers-tray")
    hl.exec_cmd("genesi-ports-tray")
    hl.exec_cmd("genesi-studio-tray")
    -- First-login default scheme = "dynamic", the only one with both a light
    -- and a dark mode. Runs once (marker); a scheme picked later is kept.
    hl.exec_cmd("sh -c 'm=\"$HOME/.config/caelestia/.genesi-scheme-init\"; [ -e \"$m\" ] && exit 0; for i in 1 2 3 4 5 6; do if caelestia scheme set --name dynamic; then mkdir -p \"$HOME/.config/caelestia\"; touch \"$m\"; break; fi; sleep 3; done'")
    -- Qt apps follow caelestia's scheme through qt6ct.
    hl.exec_cmd("genesi-caelestia-theme-sync --watch")
end)

