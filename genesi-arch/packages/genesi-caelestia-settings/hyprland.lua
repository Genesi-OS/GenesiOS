local mod = "SUPER"

-- Apps
hl.bind(mod .. " + Return", hl.dsp.exec_cmd(terminal))
hl.bind(mod .. " + E", hl.dsp.exec_cmd(fileManager))
hl.bind(mod .. " + B", hl.dsp.exec_cmd(browser))
hl.bind(mod .. " + Q", hl.dsp.window.close())
hl.bind(mod .. " + M", hl.dsp.exit())
hl.bind(mod .. " + V", hl.dsp.window.float({ action = "toggle" }))
hl.bind(mod .. " + P", hl.dsp.window.pseudo())
hl.bind(mod .. " + J", hl.dsp.layout("togglesplit"))
hl.bind(mod .. " + F", hl.dsp.window.fullscreen({ mode = "fullscreen" }))

-- caelestia shell drawers (launcher / session / clipboard).
hl.bind(mod .. " + Space", hl.dsp.exec_cmd("caelestia shell drawers toggle launcher"))
-- Tapping SUPER alone opens the launcher too (Windows-like). Hyprland skips a
-- release bind when SUPER was part of another combo, so SUPER+1 does not.
hl.bind("SUPER + SUPER_L", hl.dsp.exec_cmd("caelestia shell drawers toggle launcher"), { release = true })
hl.bind(mod .. " + X", hl.dsp.exec_cmd("caelestia shell drawers toggle session"))
-- Fallback launcher if the caelestia drawer is unavailable.
hl.bind(mod .. " + D", hl.dsp.exec_cmd("fuzzel"))
-- Clipboard history picker.
hl.bind(mod .. " + C", hl.dsp.exec_cmd("cliphist list | fuzzel --dmenu | cliphist decode | wl-copy"))

-- Screenshots.
hl.bind("Print", hl.dsp.exec_cmd("caelestia screenshot"))
hl.bind(mod .. " + S", hl.dsp.exec_cmd("caelestia screenshot -r"))

-- Display: scale and rotation from the keyboard. `-` is the screen in use.
hl.bind(mod .. " + equal", hl.dsp.exec_cmd("genesi-display scale - up"))
hl.bind(mod .. " + minus", hl.dsp.exec_cmd("genesi-display scale - down"))
hl.bind(mod .. " + SHIFT + R", hl.dsp.exec_cmd("genesi-display rotate - cycle"))

-- Brightness / volume (OSDs are drawn by caelestia). Work on the lock screen
-- and repeat while held, as before.
local locked_repeating = { locked = true, repeating = true }
hl.bind("XF86MonBrightnessUp", hl.dsp.exec_cmd("brightnessctl set 5%+"), locked_repeating)
hl.bind("XF86MonBrightnessDown", hl.dsp.exec_cmd("brightnessctl set 5%-"), locked_repeating)
hl.bind("XF86AudioRaiseVolume", hl.dsp.exec_cmd("wpctl set-volume @DEFAULT_AUDIO_SINK@ 5%+"), locked_repeating)
hl.bind("XF86AudioLowerVolume", hl.dsp.exec_cmd("wpctl set-volume @DEFAULT_AUDIO_SINK@ 5%-"), locked_repeating)
hl.bind("XF86AudioMute", hl.dsp.exec_cmd("wpctl set-mute @DEFAULT_AUDIO_SINK@ toggle"), { locked = true })

-- Focus movement
hl.bind(mod .. " + left", hl.dsp.focus({ direction = "left" }))
hl.bind(mod .. " + right", hl.dsp.focus({ direction = "right" }))
hl.bind(mod .. " + up", hl.dsp.focus({ direction = "up" }))
hl.bind(mod .. " + down", hl.dsp.focus({ direction = "down" }))

-- Workspaces 1-10 (SUPER+0 is workspace 10)
for i = 1, 10 do
    local key = i % 10
    hl.bind(mod .. " + " .. key, hl.dsp.focus({ workspace = i }))
    hl.bind(mod .. " + SHIFT + " .. key, hl.dsp.window.move({ workspace = i }))
end

-- Mouse window management
