"""
genesi_hypr_lua -- Genesi's hyprlang drop-ins, spoken in Hyprland's Lua.

Hyprland 0.57 reads only hyprland.lua, and it removed `hyprctl keyword`. Three
Genesi tools keep a drop-in of their own settings (genesi-center-set,
genesi-display, genesi-input), and each went on writing a .conf that 0.57
never reads and running a `keyword` that 0.57 refuses -- the setting looked
saved and did nothing.

The .conf stays the tools' source of truth: it is what 0.54-0.56 load, and
every tool already reads it back. Beside it, a Lua TWIN is generated from it
after every write (genesi-center.conf -> genesi-center.lua), and Genesi's
hyprland.lua loads the twins at its end. Deriving one from the other, instead
of keeping two writers, means the two can never disagree about what is set.

Only the shapes those tools write are translated: `a:b:c = v`, `monitor =`,
`workspace =`, `bind =`, `unbind =`. Anything else is written as a comment --
a guessed translation that does something unintended is worse than a line the
person can see was skipped. Every statement runs on its own, so one bad value
costs that value, not the rest of the file.

Installed to /usr/lib/genesi by genesi-caelestia-settings; the tools import it
when it is there and skip the twin when it is not (no Genesi hyprland.lua is
then loading it anyway).
"""
import os
import re
import subprocess

GENERATED = "-- Generated by Genesi from %s. Edit the app (or the .conf), not this file."


def lua_str(s):
    """A Lua string literal. Not json.dumps: Lua has no \\uXXXX escape."""
    out = []
    for ch in str(s):
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ord(ch) < 32 or ord(ch) == 127:
            out.append("\\%03d" % ord(ch))
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def lua_key(k):
    return k if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", k) else "[%s]" % lua_str(k)


NUM = re.compile(r"[+-]?(\d+\.?\d*|\.\d+)")


def lua_value(v):
    """hyprlang has no types in the text; Hyprland's Lua side accepts a number
    for bools (0/1) and for strings, so numbers go as numbers, the rest as text."""
    v = str(v).strip()
    if NUM.fullmatch(v):
        return v
    if v in ("true", "false"):
        return v
    return lua_str(v)


def config_call(option, value):
    """`input:touchpad:tap-to-click = 1` -> hl.config({ input = { touchpad = { ["tap-to-click"] = 1 } } })"""
    parts = [p.strip() for p in option.split(":") if p.strip()]
    if not parts:
        return None
    body = lua_value(value)
    for p in reversed(parts):
        body = "{ %s = %s }" % (lua_key(p), body)
    return "hl.config(%s)" % body


def combo(mods, key):
    """`SUPER SHIFT`, `K` -> "SUPER + SHIFT + K" (the 0.57 key string)."""
    parts = [m for m in re.split(r"[\s_+]+", mods.strip().upper()) if m] + [key.strip()]
    return " + ".join(parts)


DIRS = ("l", "r", "u", "d", "left", "right", "up", "down")


def dispatcher(name, arg):
    """A legacy dispatcher + argument as an hl.dsp expression, or None."""
    a = (arg or "").strip()
    if name == "exec":
        return "hl.dsp.exec_cmd(%s)" % lua_str(a) if a else None
    simple = {
        "killactive": "hl.dsp.window.close()",
        "togglefloating": 'hl.dsp.window.float({ action = "toggle" })',
        "pseudo": "hl.dsp.window.pseudo()",
        "togglesplit": 'hl.dsp.layout("togglesplit")',
        "exit": "hl.dsp.exit()",
        "pin": "hl.dsp.window.pin()",
        "centerwindow": "hl.dsp.window.center()",
        "fakefullscreen": 'hl.dsp.window.fullscreen_state({ internal = 0, client = 2, action = "toggle" })',
    }
    if name in simple:
        return simple[name]
    if name == "fullscreen":
        return 'hl.dsp.window.fullscreen({ mode = "%s" })' % ("maximized" if a == "1" else "fullscreen")
    if name == "workspace" and a:
        return "hl.dsp.focus({ workspace = %s })" % lua_str(a)
    if name == "movetoworkspace" and a:
        return "hl.dsp.window.move({ workspace = %s })" % lua_str(a)
    if name == "movetoworkspacesilent" and a:
        return "hl.dsp.window.move({ workspace = %s, follow = false })" % lua_str(a)
    if name == "movefocus" and a in DIRS:
        return "hl.dsp.focus({ direction = %s })" % lua_str(a)
    if name == "movewindow" and a in DIRS:
        return "hl.dsp.window.move({ direction = %s })" % lua_str(a)
    if name == "resizeactive":
        xy = a.split()
        if len(xy) == 2 and all(NUM.fullmatch(n) for n in xy):
            return "hl.dsp.window.resize({ x = %s, y = %s, relative = true })" % tuple(xy)
        return None
    if name == "layoutmsg" and a:
        return "hl.dsp.layout(%s)" % lua_str(a)
    if name == "togglespecialworkspace":
        return "hl.dsp.workspace.toggle_special(%s)" % (lua_str(a) if a else "")
    return None


MONITOR_INT = {"transform", "vrr", "bitdepth"}
MONITOR_STR = {"mirror", "cm", "sdrbrightness", "sdrsaturation"}


def monitor_call(value):
    """`DP-1,2560x1440@144,0x0,1.25,transform,1` -> hl.monitor({...})."""
    f = [p.strip() for p in value.split(",")]
    if len(f) >= 2 and f[1] == "disable":
        return "hl.monitor({ output = %s, disabled = true })" % lua_str(f[0])
    if len(f) < 4:
        return None
    fields = ["output = %s" % lua_str(f[0]), "mode = %s" % lua_str(f[1]),
              "position = %s" % lua_str(f[2]), "scale = %s" % lua_str(f[3])]
    rest = f[4:]
    if len(rest) % 2:
        return None
    for k, v in zip(rest[::2], rest[1::2]):
        if k in MONITOR_INT and re.fullmatch(r"-?\d+", v):
            fields.append("%s = %s" % (k, v))
        elif k in MONITOR_STR:
            fields.append("%s = %s" % (k, lua_str(v)))
        else:
            return None
    return "hl.monitor({ %s })" % ", ".join(fields)


def workspace_call(value):
    """`1, monitor:DP-1, default:true` -> hl.workspace_rule({...})."""
    f = [p.strip() for p in value.split(",") if p.strip()]
    if not f:
        return None
    fields = ["workspace = %s" % lua_str(f[0])]
    for p in f[1:]:
        if ":" not in p:
            return None
        k, v = (x.strip() for x in p.split(":", 1))
        if k not in ("monitor", "default", "persistent"):
            return None
        fields.append("%s = %s" % (k, v if v in ("true", "false") else lua_str(v)))
    return "hl.workspace_rule({ %s })" % ", ".join(fields)


def line_to_lua(line):
    """One drop-in line -> one Lua statement, or None when it is not ours to guess."""
    m = re.match(r"^\s*([A-Za-z_][\w.:-]*)\s*=\s*(.*?)\s*$", line)
    if not m:
        return None
    key, val = m.group(1), m.group(2)
    if key == "monitor":
        return monitor_call(val)
    if key == "workspace":
        return workspace_call(val)
    if key == "unbind":
        f = [p.strip() for p in val.split(",")]
        return "hl.unbind(%s)" % lua_str(combo(f[0], f[1])) if len(f) == 2 and f[1] else None
    if key == "bind":
        f = [p.strip() for p in val.split(",", 3)]
        if len(f) < 3 or not f[1]:
            return None
        d = dispatcher(f[2], f[3] if len(f) > 3 else "")
        return "hl.bind(%s, %s)" % (lua_str(combo(f[0], f[1])), d) if d else None
    if key in ("source", "exec", "exec-once", "env", "windowrule", "layerrule"):
        return None
    if re.fullmatch(r"[a-z_-]+(:[a-z0-9_.-]+)+", key):
        return config_call(key, val)
    return None


def conf_to_lua(text, origin):
    out = [GENERATED % origin,
           "local function apply(what, fn)",
           "    local ok, err = pcall(fn)",
           "    if not ok then",
           '        hl.notification.create({ text = "Genesi: %s: " .. what .. ": " .. tostring(err), timeout = 10000 })' % origin,
           "    end",
           "end",
           ""]
    for raw in text.splitlines():
        line = raw.strip()
        if not line:
            continue
        if line.startswith("#"):
            out.append("-- " + line.lstrip("#").strip())
            continue
        stmt = line_to_lua(line)
        if stmt is None:
            out.append("-- not translated: " + line)
        else:
            out.append("apply(%s, function() %s end)" % (lua_str(line), stmt))
    return "\n".join(out) + "\n"


def write_twin(conf_path, owner=None):
    """Regenerate <name>.lua from <name>.conf beside it. Returns the path."""
    lua_path = conf_path[:-5] + ".lua" if conf_path.endswith(".conf") else conf_path + ".lua"
    try:
        text = open(conf_path, encoding="utf-8", errors="replace").read()
    except OSError:
        text = ""
    tmp = "%s.genesi-tmp.%d" % (lua_path, os.getpid())
    with open(tmp, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(conf_to_lua(text, os.path.basename(conf_path)))
    if owner is not None:
        try:
            uid, gid = (int(x) for x in owner.split(":"))
            os.chown(tmp, uid, gid)
        except (OSError, ValueError):
            pass
    os.replace(tmp, lua_path)
    return lua_path


_LUA = None


def lua_session():
    """Is the running Hyprland on the Lua config (0.55+ with hyprland.lua)?
    `eval` answers "ok" only there; hyprctl exits 0 either way."""
    global _LUA
    if _LUA is None:
        _LUA = False
        if os.environ.get("HYPRLAND_INSTANCE_SIGNATURE"):
            try:
                p = subprocess.run(["hyprctl", "eval", "return 1"], capture_output=True, text=True, timeout=8)
                _LUA = p.stdout.strip().startswith("ok")
            except (OSError, subprocess.SubprocessError):
                _LUA = False
    return _LUA


def run(stmt):
    """Apply one Lua statement now. Returns (ok, answer)."""
    try:
        p = subprocess.run(["hyprctl", "eval", stmt], capture_output=True, text=True, timeout=8)
    except (OSError, subprocess.SubprocessError) as e:
        return False, str(e)
    answer = (p.stdout + p.stderr).strip()
    return answer.startswith("ok"), answer
