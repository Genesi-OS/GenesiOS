def greeter_archive(repo_key):
    """The tarball, downloaded once however many themes come out of it."""
    if repo_key not in _ARCHIVES:
        repo, ref = GREETER_REPOS[repo_key]
        url = "https://codeload.github.com/%s/tar.gz/%s" % (repo, ref)
        print("  fetching %s" % url)
        data = get(url, binary=True)
        if not data.startswith(b"\x1f\x8b"):
            raise SystemExit("%s did not answer with a gzip archive" % url)
        _ARCHIVES[repo_key] = (url, data)
    return _ARCHIVES[repo_key]


def archive_root(repo_key):
    repo, ref = GREETER_REPOS[repo_key]
    return "%s-%s" % (repo.split("/")[1], ref)


def greeter_members(repo_key):
    import tarfile
    _, data = greeter_archive(repo_key)
    return tarfile.open(fileobj=io.BytesIO(data), mode="r:gz")


def tree_digest_of(repo_key, subpath):
    """The same digest genesi-store-helper computes after it unpacks.

    Every regular file under the subtree, by relative path in sorted order,
    path then bytes. Not the archive's checksum: see the note at the top of
    this section, and ci/store-test.py, which runs this function and the
    helper's over the same tree and fails if they ever disagree.
    """
    prefix = "/".join(x for x in (archive_root(repo_key), subpath) if x)
    files = {}
    with greeter_members(repo_key) as tar:
        for member in tar:
            if not member.isfile():
                continue
            name = member.name
            if name != prefix and not name.startswith(prefix + "/"):
                continue
            rel = name[len(prefix):].lstrip("/")
            files[rel] = tar.extractfile(member).read()
    if not files:
        raise SystemExit("nothing under %s in the %s archive"
                         % (prefix, repo_key))
    digest = hashlib.sha256()
    for rel in sorted(files):
        digest.update(rel.encode("utf-8"))
        digest.update(b"\0")
        digest.update(files[rel])
        digest.update(b"\0")
    return digest.hexdigest(), files


def greeter_needs(files):
    """What this theme's own QML says it cannot run without."""
    needs = set()
    for rel, blob in files.items():
        if not rel.endswith(".qml"):
            continue
        text = blob.decode("utf-8", "replace")
        for line in text.splitlines():
            line = line.strip()
            if not line.startswith("import "):
                continue
            module = line.split()[1]
            for bad in QT5_ONLY:
                if module == bad or module.startswith(bad + "."):
                    raise SystemExit(
                        "%s imports %s, which is Qt5 only -- on Genesi that "
                        "theme is a black screen at boot" % (rel, module))
            for known, package in MODULE_PACKAGES.items():
                if module == known or module.startswith(known + "."):
                    if package:
                        needs.add(package)
                    break
    if any(rel.endswith(".svg") for rel in files):
        needs.add("qt6-svg")
    return sorted(needs)


def greeter_confs(files):
    return sorted(rel for rel in files if rel.endswith(".conf"))


def greeter_picture(item_id, key, where):
    """Where the screenshot IS, verified now and fetched on the machine.

    These pictures are not ours. They are the authors' screenshots, and some
    of what is in them is not even theirs -- the astronaut wallpapers are
    described by their own README as "copied from one user to another", and
    two of them are frames of a cartoon and of a commercial game. Shipping
    them inside a Genesi package would be Genesi redistributing that. Naming
    them is not: the picture comes from the same place the theme does, pinned
    to the same kind of commit, checked against the same kind of digest.

    So this downloads the file ONCE, at build time, to prove the link works
    and to record what the bytes are -- and then throws the bytes away.

    A `tar:` path is relative to the root of the downloaded archive, which is
    also its path in the repository, so it can be named directly rather than
    making somebody fetch twenty megabytes of theme to see one screenshot.
    """
    kind, _, rest = where.partition(":")
    if kind == "url":
        url = GREETER_PICTURES.get(rest) or (ASTRONAUT_SHOTS + rest)
    else:
        repo, ref = GREETER_REPOS[REPO_OF[key]]
        url = "https://raw.githubusercontent.com/%s/%s/%s" % (repo, ref, rest)
    data = get(url, binary=True)
    for mime, head in (("image/png", b"\x89PNG"), ("image/jpeg", b"\xff\xd8\xff")):
        if data.startswith(head):
            break
    else:
        raise SystemExit("%s is not a picture -- the link is broken" % url)
    if len(data) > MAX_SHOT_BYTES:
        raise SystemExit("%s is %.1f MB; a screenshot stops at %d MB"
                         % (url, len(data) / 1048576.0,
                            MAX_SHOT_BYTES // (1 << 20)))
    return {"url": url, "type": mime, "bytes": len(data),
            "sha256": hashlib.sha256(data).hexdigest()}


