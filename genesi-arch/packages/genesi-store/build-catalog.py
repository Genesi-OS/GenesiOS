# Where build-time downloads are kept between runs. Outside the repository,
# because it is scratch: describing the qylock collection means fetching ~570
# MB of theme, and a build that pays that again to change one blurb is a build
# nobody runs twice. Delete it to force a fresh fetch.
CACHE = os.path.join(tempfile.gettempdir(), "genesi-store-build-cache")


def get(url, binary=False):
    cached = os.path.join(CACHE, hashlib.sha256(url.encode("utf-8")).hexdigest())
    if os.path.exists(cached):
        with open(cached, "rb") as fh:
            data = fh.read()
        return data if binary else data.decode("utf-8")
    request = urllib.request.Request(url, headers={"User-Agent": "genesi-store-build"})
    # Some of these are fourteen-megabyte backgrounds, and describing a whole
    # collection is hundreds of requests -- at that volume a read timing out
    # is not an error, it is Tuesday. Three tries, longer each time.
    data = None
    for attempt in range(3):
        try:
            with urllib.request.urlopen(request, timeout=60 * (attempt + 1)) as response:
                data = response.read()
            break
        except (urllib.error.URLError, OSError) as exc:
            if attempt == 2:
                raise SystemExit("could not fetch %s: %s" % (url, exc))
            sys.stderr.write("  retrying %s (%s)\n"
                             % (url.rsplit("/", 1)[-1], exc))
            time.sleep(2 * (attempt + 1))
    os.makedirs(CACHE, exist_ok=True)
    tmp = cached + ".part"
    with open(tmp, "wb") as fh:
        fh.write(data)
    os.replace(tmp, cached)
    return data if binary else data.decode("utf-8")


def scheme_colours(family, flavour, mode):
    """The five colours a theme card is painted in, from caelestia's own file."""
    url = "%s%s/%s/%s.txt" % (SCHEME_REPO, family, flavour, mode)
    want = ("background", "onBackground", "primary", "secondary", "tertiary",
            "surface")
    found = {}
    for line in get(url).splitlines():
        parts = line.split()
        if len(parts) == 2 and parts[0] in want:
            found[parts[0]] = "#" + parts[1].lower()
    missing = [k for k in want if k not in found]
    if missing:
        raise SystemExit("scheme %s/%s/%s has no %s"
                         % (family, flavour, mode, ", ".join(missing)))
    return found


def thumbnail(ident, data, filename):
    """A small picture of the wallpaper, shipped IN the package.

    Without this a decor card is a grey rectangle with a file size in it until
    somebody downloads the wallpaper -- which is backwards, because the picture
    is the reason to download it. 480px of JPEG is about 25 kB, so eighteen of
    them cost less than half a megabyte and the shelf becomes a shelf of
    pictures. They are also what the lock screens, the rices and the
    collections are drawn over, so one download feeds four shelves.
    """
    from PySide6.QtGui import QGuiApplication, QImage
    from PySide6.QtCore import Qt
    global _APP
    try:
        _APP
    except NameError:
        _APP = QGuiApplication([])
    image = QImage.fromData(data)
    if image.isNull():
        raise SystemExit("could not read %s as an image" % filename)
    # 480 was chosen when a card was a small tile in a grid. The shelf is a
    # mosaic now: a wide card is most of the window, and the detail sheet
    # draws the same picture across the top of it. On a 1900px window that was
    # a 480px JPEG stretched nearly four times, which looks exactly as bad as
    # it sounds.
    #
    # 1280 covers the widest card on a 4K screen without being a second copy
    # of the wallpaper: these stay around 120 kB each.
    small = image.scaledToWidth(1280, Qt.SmoothTransformation)
    out = os.path.join(HERE, "catalog", "thumbs")
    os.makedirs(out, exist_ok=True)
    name = ident + ".jpg"
    if not small.save(os.path.join(out, name), "JPG", 82):
        raise SystemExit("could not write the thumbnail for " + ident)
    return name


MIN_WALL_WIDTH = 1920


def wallpaper_size(data):
    """The pixel size of a downloaded wallpaper, or (0, 0) if unreadable."""
    from PySide6.QtGui import QGuiApplication, QImage
    global _APP
    try:
        _APP
    except NameError:
        _APP = QGuiApplication([])
    image = QImage.fromData(data)
    return image.width(), image.height()


def wallpaper_asset(filename):
    url = WALL_REPO + filename
    data = get(url, binary=True)
    kind = "image/png" if filename.endswith(".png") else "image/jpeg"
    head = {"image/png": b"\x89PNG", "image/jpeg": b"\xff\xd8\xff"}[kind]
    if not data.startswith(head):
        raise SystemExit("%s is not %s -- the link is broken" % (url, kind))
    width, height = wallpaper_size(data)
    if width and width < MIN_WALL_WIDTH:
        raise SystemExit("%s is only %dx%d; a wallpaper this shelf offers has "
                         "to be at least %d wide or it is scaled up on every "
                         "machine Genesi installs on"
                         % (filename, width, height, MIN_WALL_WIDTH))
    # The bytes come back too: the thumbnail is made from the file we just
    # verified, not from a second download of something that may differ.
    return ({"url": url, "type": kind, "bytes": len(data),
             "width": width, "height": height,
             "sha256": hashlib.sha256(data).hexdigest()}, data)


# ── Two languages, English first ───────────────────────────────────────────
#
# The tables in this file are written in Portuguese because that is the
# language the shelf was designed in and the one the copy was tuned in. What
# SHIPS leads with English, because the store is part of an operating system
# people install from anywhere, and falls back to the machine's own language
# when it has one.
#
# So every card carries both: `name` and `blurb` are English, `name_pt` and
# `blurb_pt` are what is written below. The app picks by locale.
#
# The translations live in one file rather than inline in each table so that
# adding a card does not mean editing two places -- and so that the check
# below can be exhaustive: a string with no translation FAILS THE BUILD
# rather than shipping half-translated, which is the state every
# half-internationalised app is permanently stuck in.
from catalog_en import ENGLISH, SAME  # noqa: E402


def englished(text, what):
    if text is None or text == "":
        return text
    if text in SAME:
        return text
    if text not in ENGLISH:
        MISSING.add("%s: %r" % (what, text))
        return text
    return ENGLISH[text]


MISSING = set()


def bilingual(item):
    """Return the item with English up front and Portuguese beside it."""
    out = dict(item)
    for field in ("name", "blurb"):
        if field in out:
            out[field + "_pt"] = out[field]
            out[field] = englished(out[field], field)
    if out.get("tags"):
        out["tags_pt"] = list(out["tags"])
        out["tags"] = [englished(t, "tag") for t in out["tags"]]
    return out


def bilingual_section(section):
    out = dict(section)
    out["label_pt"] = out["label"]
    # These already carried an English label; use it and drop the duplicate.
    out["label"] = out.pop("label_en", None) or englished(out["label"], "label")
    if "blurb" in out:
        out["blurb_pt"] = out["blurb"]
        out["blurb"] = englished(out["blurb"], "section blurb")
    return out


def build():
    previous = {}
    if os.path.exists(OUT):
        with io.open(OUT, encoding="utf-8") as fh:
            for item in json.load(fh).get("items", []):
                previous[item["id"]] = item

    items = []

    # ── Themes ─────────────────────────────────────────────────────────────
    for family, flavour, mode, name, blurb in SCHEMES:
        ident = "theme-%s-%s-%s" % (family, flavour, mode)
        # Offline reuses the COLOURS, which came off the network, and rebuilds
        # the item around them. Reusing the whole item meant a change to a name
        # or a tag silently did not happen on an offline build.
        if OFFLINE and ident in previous:
            colours = {"background": previous[ident]["preview"]["background"],
                       "onBackground": previous[ident]["preview"]["ink"],
                       "surface": previous[ident]["preview"].get("surface", previous[ident]["preview"]["background"]),
                       "primary": previous[ident]["preview"]["colours"][0],
                       "secondary": previous[ident]["preview"]["colours"][1],
                       "tertiary": previous[ident]["preview"]["colours"][2]}
        else:
            colours = scheme_colours(family, flavour, mode)
        items.append({
            "id": ident,
            "section": "themes",
            "name": name,
            "blurb": blurb,
            "author": "caelestia / %s" % family,
            "mode": mode,
            "tags": ["escuro" if mode == "dark" else "claro", family],
            "preview": {"kind": "scheme",
                        "background": colours["background"],
                        "surface": colours.get("surface", colours["background"]),
                        "ink": colours["onBackground"],
                        "colours": [colours["primary"], colours["secondary"],
                                    colours["tertiary"]]},
            "actions": [{"action": "scheme", "name": family,
                         "flavour": flavour, "mode": mode}],
        })

    # ── Decor: wallpapers ──────────────────────────────────────────────────
    for ident, filename, name, blurb, tags in WALLS:
        full = "wall-" + ident
        thumb = full + ".jpg"
        have_thumb = os.path.exists(os.path.join(HERE, "catalog", "thumbs", thumb))
        if OFFLINE and full in previous and have_thumb:
            asset = previous[full]["assets"]["picture"]
        else:
            asset, raw = wallpaper_asset(filename)
            thumb = thumbnail(full, raw, filename)
        items.append({
            "id": full,
            "section": "decor",
            "name": name,
            "blurb": blurb,
            "author": "D3Ext/aesthetic-wallpapers",
            "license": "MIT",
            "source": "https://github.com/D3Ext/aesthetic-wallpapers",
            "tags": tags,
            "preview": {"kind": "image", "thumb": thumb, "asset": "picture"},
            "assets": {"picture": asset},
            "actions": [{"action": "wallpaper", "asset": "picture"}],
        })

    # ── Bar styles ─────────────────────────────────────────────────────────
    for preset, name, blurb in BARS:
        items.append({
            "id": "bar-" + preset.split("-", 1)[1],
            "section": "bars",
            "name": name,
            "blurb": blurb,
            "author": "Genesi",
            "tags": ["barra"],
            "preview": dict({"kind": "bar", "preset": preset},
                            **bar_shape(preset)),
            "actions": [{"action": "bar", "preset": preset}],
        })

    for extra in (lockscreens(), fastfetch(), rices(previous), bundles(),
                  plugins(), factory()):
        items.extend(extra)

    # The login screens that are downloaded rather than shipped. The map they
    # point into is what makes them data: a card carries a key, and the key
    # resolves -- in the store, and again in the helper, out of the copy under
    # /usr/share that only root can write -- to a URL, a digest and a
    # destination this build decided.
    greeter_specs = {}
    if OFFLINE:
        if os.path.exists(OUT):
            with io.open(OUT, encoding="utf-8") as fh:
                old = json.load(fh)
            greeter_specs = old.get("greeters") or {}
            # Those items were written out bilingual -- English in `name`,
            # Portuguese in `name_pt` -- and bilingual() below translates
            # `name` again. Put them back the way the tables write them, or
            # every reused login screen is an English string with "no
            # English" and the offline build cannot finish.
            for i in old.get("items", []):
                if not any(a.get("action") == "greeter"
                           for a in i.get("actions", [])):
                    continue
                i = dict(i)
                for field in ("name", "blurb", "tags"):
                    if field + "_pt" in i:
                        i[field] = i.pop(field + "_pt")
                items.append(i)
    else:
        greeter_specs, greeter_items = greeters()
        items.extend(greeter_items)

    # English up front, Portuguese beside it. A string with no translation
    # stops the build rather than shipping a shelf that is half one language
    # and half the other.
    data = {
        "version": 1,
        "updated": time.strftime("%Y-%m-%d"),
        "sections": [bilingual_section(x) for x in SECTIONS],
        "greeters": greeter_specs,
        "items": [bilingual(i) for i in items],
    }
    if MISSING:
        raise SystemExit("no English for %d string(s):\n  %s"
                         % (len(MISSING),
                            "\n  ".join(sorted(MISSING)[:12])))

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with io.open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        json.dump(data, fh, indent=1, ensure_ascii=False, sort_keys=False)
        fh.write("\n")
    print("catalog: %d items across %d sections" % (len(items), len(SECTIONS)))
    for section in SECTIONS:
        count = len([i for i in items if i["section"] == section["id"]])
        print("  %-12s %d" % (section["id"], count))


