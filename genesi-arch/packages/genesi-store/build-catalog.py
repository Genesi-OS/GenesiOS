def theme_still(spec):
    """The sharpest picture of the theme ITSELF, or None.

    Backgrounds only. The largest file is often a logo or an avatar, and
    "biggest image" would have put a 2000x2000 Genshin wordmark on a card
    whose job is to show what the screen looks like.
    """
    best = None
    for entry in spec["files"]:
        path = entry["path"].lower()
        if not path.endswith((".png", ".jpg", ".jpeg")):
            continue
        stem = os.path.splitext(os.path.basename(path))[0]
        if any(word in stem for word in LOGO_NAMES):
            continue
        if best is None or entry["bytes"] > best["bytes"]:
            best = entry
    if not best:
        return None
    raw = get(spec["base"] + "/" + urllib.parse.quote(best["path"]), binary=True)
    width, _height = wallpaper_size(raw)
    kind = "image/png" if best["path"].lower().endswith(".png") else "image/jpeg"
    return {"url": spec["base"] + "/" + urllib.parse.quote(best["path"]),
            "type": kind, "bytes": best["bytes"], "sha256": best["sha256"],
            "width": width}


def theme_motion(key, subdir):
    """The author's animated preview of the theme, or None.

    qylock ships one per theme in Assets/, which matters because nineteen of
    these have an MP4 for a background and no still image at all. They are
    400x225 every one of them, though -- fine as the thing that MOVES when
    you point at a card, far too small to BE the card.
    """
    repo, ref = FILE_REPOS["qylock"]
    flat = lambda name: re.sub(r"[^a-z0-9]", "", name.lower())
    assets = {flat(os.path.splitext(os.path.basename(p))[0]): p
              for p in repo_tree(repo, ref)
              if p.startswith("Assets/") and p.lower().endswith((".gif", ".png"))}
    want = flat(subdir)
    aliases = {"windows7": "win7", "lastofus": "thelastofus"}
    path = (assets.get(want) or assets.get(want.replace("the", "", 1))
            or assets.get(flat(aliases.get(want, ""))))
    if not path:
        return None
    url = ("https://raw.githubusercontent.com/%s/%s/%s"
           % (repo, ref, urllib.parse.quote(path)))
    raw = get(url, binary=True)
    width, _height = wallpaper_size(raw)
    return {"url": url,
            "type": "image/gif" if path.lower().endswith(".gif") else "image/png",
            "bytes": len(raw), "sha256": hashlib.sha256(raw).hexdigest(),
            "width": width}


def theme_backdrop(key, spec, subdir):
    """What a collection theme shows on its card: a still, and maybe motion.

    The still is the theme's own background where it has one big enough --
    two and a half thousand pixels wide in places, against the 400x225 the
    author's GIF is. The GIF is kept as the thing that plays when you point
    at the card, so the sharp picture is what you see and the motion is there
    when you want it.

    Eighteen of these are video-backgrounded and have no still at all. For
    those the GIF IS the card, and the drawing fills the rest of it with a
    blurred copy rather than stretching 400 pixels across a window.
    """
    still = theme_still(spec)
    motion = theme_motion(key, subdir)
    if not still and not motion:
        raise SystemExit("%s has no preview anywhere in the collection" % key)
    # A sharp still wins. Below that the author's animation is the better
    # picture, because it is at least of the whole screen. A small still is
    # still better than nothing -- MIN_SHOT_WIDTH is a preference, not a bar
    # to clear, and one theme (ninesols) has only a 1080px background and no
    # animation at all.
    if still and still["width"] >= MIN_SHOT_WIDTH:
        shot = still
    elif motion:
        shot = motion
    else:
        shot = still
    out = dict(shot)
    if motion and motion is not shot:
        out["motion"] = motion
    return out


def repo_tree(repo, ref):
    """Every file in a repository at one commit. One API call, not 604 MB."""
    key = (repo, ref)
    if key not in _TREES:
        data = json.loads(get("https://api.github.com/repos/%s/git/trees/%s"
                              "?recursive=1" % (repo, ref)))
        if data.get("truncated"):
            raise SystemExit("the file list for %s is truncated, so this build "
                             "cannot describe it completely" % repo)
        _TREES[key] = sorted(b["path"] for b in data.get("tree", [])
                             if b.get("type") == "blob")
    return _TREES[key]


def theme_files(repo_key, subdir):
    """One theme out of a collection: its files, their digests, and the bytes.

    Everything is fetched here, at build time, to prove the links work and to
    record what the bytes are. The bytes are returned so the rest of the build
    can read the theme's QML imports and its config list out of them, exactly
    as it does for a theme that arrived in a tarball -- and then they are
    thrown away. What ships is paths and digests.
    """
    repo, ref = FILE_REPOS[repo_key]
    prefix = subdir.rstrip("/") + "/"
    paths = [p for p in repo_tree(repo, ref) if p.startswith(prefix)]
    if not paths:
        raise SystemExit("%s has no %s at %s" % (repo, subdir, ref[:8]))

    files, fetched, total = [], {}, 0
    for path in paths:
        rel = path[len(prefix):]
        # A .gitkeep holding an empty font directory is not part of the theme.
        if not rel or os.path.basename(rel) == ".gitkeep":
            continue
        raw = get("https://raw.githubusercontent.com/%s/%s/%s"
                  % (repo, ref, urllib.parse.quote(path)), binary=True)
        total += len(raw)
        if total > MAX_THEME_BYTES:
            raise SystemExit("%s/%s is over %d MB"
                             % (repo, subdir, MAX_THEME_BYTES // (1 << 20)))
        files.append({"path": rel, "bytes": len(raw),
                      "sha256": hashlib.sha256(raw).hexdigest()})
        fetched[rel] = raw
    if not files:
        raise SystemExit("%s/%s has no files worth installing" % (repo, subdir))

    # The same digest the helper will compute once it has written them: path,
    # then bytes, sorted by path. ci/store-test.py runs the helper's own
    # function over a real directory and compares the two.
    digest = hashlib.sha256()
    for entry in sorted(files, key=lambda f: f["path"]):
        digest.update(entry["path"].encode("utf-8"))
        digest.update(b"\0")
        digest.update(fetched[entry["path"]])
        digest.update(b"\0")
    return files, digest.hexdigest(), fetched


def greeters():
    """The greeters map and the cards that point into it."""
    specs = {}
    trees = {}
    for key, repo_key, subpath, install_as, author, licence in GREETERS:
        digest, files = tree_digest_of(repo_key, subpath)
        trees[key] = files
        repo, ref = GREETER_REPOS[repo_key]
        url, data = greeter_archive(repo_key)
        meta = files.get("metadata.desktop", b"").decode("utf-8", "replace")
        if "QtVersion=6" not in meta.replace(" ", ""):
            raise SystemExit("%s does not say QtVersion=6, so it is a Qt5 "
                             "theme and would not come up" % key)
        specs[key] = {
            "name": repo.split("/")[1],
            "source": "https://github.com/%s/tree/%s" % (repo, ref),
            "author": author,
            "license": licence,
            "url": url,
            "sha256": hashlib.sha256(data).hexdigest(),
            "bytes": len(data),
            "subpath": "/".join(x for x in (archive_root(repo_key), subpath) if x),
            "tree": digest,
            "install_as": install_as,
            "needs": greeter_needs(files),
            "confs": greeter_confs(files),
        }

    # The collection themes: same map, same checks, described file by file.
    for ident, subdir, name, blurb, tags in QYLOCK_THEMES:
        key = "qylock-" + ident
        files, digest, fetched = theme_files("qylock", "themes/" + subdir)
        meta = fetched.get("metadata.desktop", b"").decode("utf-8", "replace")
        if "QtVersion=6" not in meta.replace(" ", ""):
            raise SystemExit("%s does not say QtVersion=6, so it is a Qt5 "
                             "theme and would not come up" % key)
        repo, ref = FILE_REPOS["qylock"]
        specs[key] = {
            "name": subdir,
            "source": "https://github.com/%s/tree/%s/themes/%s"
                      % (repo, ref, subdir),
            "author": "Darkkal44",
            "license": "GPL-3.0-or-later",
            # No `url`: there is no archive. `base` is what each file hangs
            # off, and every one of them carries its own digest.
            "base": "https://raw.githubusercontent.com/%s/%s/themes/%s"
                    % (repo, ref, urllib.parse.quote(subdir)),
            "files": files,
            "bytes": sum(f["bytes"] for f in files),
            "tree": digest,
            "install_as": "genesi-" + key,
            "needs": greeter_needs(fetched),
            "confs": greeter_confs(fetched),
        }
        trees[key] = fetched

    out = []
    for ident, subdir, name, blurb, tags in QYLOCK_THEMES:
        key = "qylock-" + ident
        spec = specs[key]
        out.append({
            "id": "login-" + key,
            "section": "login",
            "name": name,
            "blurb": blurb,
            "family": "login",
            "author": spec["author"],
            "license": spec["license"],
            "source": spec["source"],
            "tags": ["login", "antes da sessão", "qylock"] + tags,
            "needs_root": True,
            "download": spec["bytes"],
            # The card's picture is the theme's OWN background: already
            # fetched, already hashed, and the most honest preview there is,
            # because it is literally what you will be looking at.
            "preview": {"kind": "login", "theme": key,
                        "shot": theme_backdrop(key, spec, subdir)},
            "actions": [{"action": "greeter", "key": key}],
        })

    for (ident, key, conf, name, blurb, tags, picture) in GREETER_ITEMS:
        spec = specs[key]
        if conf and conf not in spec["confs"]:
            raise SystemExit("%s asks for %s, which %s does not have"
                             % (ident, conf, key))
        action = {"action": "greeter", "key": key}
        if conf:
            action["conf"] = conf
        out.append({
            "id": "login-" + ident,
            "section": "login",
            "name": name,
            "blurb": blurb,
            "family": "login",
            "author": spec["author"],
            "license": spec["license"],
            "source": spec["source"],
            "tags": ["login", "antes da sessão"] + tags,
            "needs_root": True,
            "download": spec["bytes"],
            "preview": {"kind": "login", "theme": key,
                        "shot": greeter_picture(ident, key, picture)},
            "actions": [action],
        })
    return specs, out


