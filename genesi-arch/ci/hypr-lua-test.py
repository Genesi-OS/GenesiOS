    keys = iter("ABCDEFGHIJKLMNOPQRSTUVWXYZ")
    for d in sorted(center.DISPATCHERS):
        center.cmd_newbind("SUPER ALT," + next(keys), d, samples.get(d, ""))
    twin = os.path.join(tdir, "genesi-center.lua")
