# -- nothing else still speaks only the old hyprctl ----------------------------
#
# 0.57 removed `hyprctl keyword` and made `hyprctl dispatch` take Lua. A call
# in either old form is now an error that hyprctl answers with exit status 0,
# so the feature behind it just stops, silently. Every file that still uses an
# old form must also have the Lua one (`hyprctl eval`, `hl.dsp.`, usingLua)
# right there, choosing between them.
#
# PENDING lists files not ported yet, by name, so the gap is written down
# instead of being found by a user -- and a file leaving the list is the only
# way it can shrink: a listed file that no longer needs listing fails too.
PENDING = {}
LEGACY = re.compile(r"""["']hyprctl["'],\s*["'](keyword|dispatch)["']|hyprctl\s+(keyword|dispatch)\s+[a-z]|hypr\(\s*["']keyword["']|Hyprland\.dispatch\(\s*["'][a-z]""")
MODERN = re.compile(r"""["']eval["']|hyprctl eval|hl\.dsp\.|usingLua|genesi-hypr|hlua\.run\(""")
COMMENT = re.compile(r"^\s*(#|//|\*|/\*|--)")
PKGS = os.path.join(HERE, "..", "packages")
print("== nothing speaks only the hyprctl that 0.57 removed")
legacy_only, pending_seen = [], set()
for root, dirs, files in os.walk(PKGS):
    dirs[:] = [d for d in dirs if d not in ("__pycache__", ".git", "node_modules")]
    for name in files:
        if not (name.endswith((".py", ".qml", ".sh")) or "." not in name or name == "PKGBUILD"):
            continue
        path = os.path.join(root, name)
        rel = os.path.relpath(path, PKGS).replace(os.sep, "/")
        try:
            text = open(path, encoding="utf-8").read()
        except (UnicodeDecodeError, OSError):
            continue
        code = "\n".join(l for l in text.splitlines() if not COMMENT.match(l))
        if not LEGACY.search(code):
            continue
        if rel in PENDING:
            pending_seen.add(rel)
        elif not MODERN.search(code):
            legacy_only.append(rel)
check(not legacy_only, "every hyprctl keyword/dispatch call has its Lua form beside it", legacy_only)
# The file-level check above only sees that a file KNOWS the Lua form, not
# that it acts on the answer. hyprshade is where that already went wrong once
# (our patch turned upstream's working Lua call into `keyword`), so its patch
# is held to the exact shape: Lua first, and stop there when it says "ok".
hs = open(os.path.join(PKGS, "genesi-hyprshade", "PKGBUILD"), encoding="utf-8").read()
check(re.search(r'"eval",.*?if lua\.stdout\.strip\(\) == "ok":\s*\n\s*return\s*\n.*?"keyword"', hs, re.S) is not None,
      "hyprshade sets the shader in Lua first and uses `keyword` only when Lua was refused")
for rel, why in PENDING.items():
    check(rel in pending_seen, "PENDING still needs listing: %s (%s)" % (rel, why),
          "it no longer uses the old forms -- take it off PENDING")
if PENDING:
    print("  note %d tool(s) still write hyprlang settings Hyprland 0.57 ignores: %s"
          % (len(PENDING), ", ".join(sorted(PENDING))))

