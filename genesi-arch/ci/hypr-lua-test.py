#!/usr/bin/env python3
"""
hypr-lua-test.py -- Genesi's hyprland.lua is a config Hyprland 0.57 accepts,
and it is the same desktop as hyprland.conf.

-- Why this exists --------------------------------------------------------------

Hyprland 0.57 removed hyprland.conf support: only ~/.config/hypr/hyprland.lua
is read. Every Genesi Hyprland desktop upgraded past it came up on Hyprland's
autogenerated config -- no caelestia, no bar, no keys, a "Welcome to
Hyprland" window (user report, 2026-11-08). Hyprland's Lua API does not fail
loudly either: an unknown option, rule effect or match property is a line in
`hyprctl configerrors`, and the rest of the config loads around it. So a typo
here is a desktop that looks fine and quietly lacks a feature.

This runs the shipped hyprland.lua in a real Lua interpreter against a mock
`hl` whose every name comes from Hyprland's own sources at the version we
target (ci/data/hyprland-api.json: options, dispatchers, bind flags, monitor
fields, rule effects, match properties). Anything that is not there fails.

Then it holds hyprland.lua and hyprland.conf to each other -- same keys bound,
same programs started, same windows ruled -- because Hyprland 0.54 and older
still read only the .conf, and the two files drifting apart would mean two
different desktops depending on a version number nobody looks at.

Finally the drop-ins: a missing genesi-display.lua is silent, a broken one is
reported on screen without costing the rest of the config, and user.lua loads
last.
"""
import json
import os
import re
import shutil
import sys
import tempfile

try:
    from lupa import LuaRuntime
except ImportError:
    print("lupa is not installed (pip install lupa)")
    sys.exit(1)

HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.join(HERE, "..", "packages", "genesi-caelestia-settings")
LUA = os.path.join(PKG, "hyprland.lua")
CONF = os.path.join(PKG, "hyprland.conf")
API = json.load(open(os.path.join(HERE, "data", "hyprland-api.json"), encoding="utf-8"))

failures = []


def check(cond, what, why=""):
    print(("  ok   " if cond else "  FAIL ") + what)
    if not cond:
        failures.append(what)
        if why:
            print("         " + str(why)[:600])


OPTIONS = {o.replace(".", ":") for o in API["options"]}
DISPATCHERS = set(API["dispatchers"])

MOCK = r"""
local rec = {}
local function list(name) rec[name] = rec[name] or {}; return rec[name] end
local function err(msg) table.insert(list("errors"), msg) end

hl = {}
local dsp_mt = {}
local function dispatcher(path)
    return setmetatable({}, {
        __index = function(_, k) return dispatcher(path == "" and k or path .. "." .. k) end,
        __call = function(_, ...)
            if not DISPATCHERS[path] then err("unknown dispatcher hl.dsp." .. path) end
            return { __dsp = path, args = { ... } }
        end,
    })
end
hl.dsp = dispatcher("")

local function walk(t, prefix)
    for k, v in pairs(t) do
        local path = prefix == "" and k or prefix .. ":" .. k
        if OPTIONS[path] then
            table.insert(list("options"), path)
        elseif type(v) == "table" then
            walk(v, path)
        else
            err("unknown option " .. path)
        end
    end
end
function hl.config(t) walk(t, "") end
function hl.env(k, v)
    if type(k) ~= "string" or type(v) ~= "string" then err("hl.env needs two strings: " .. tostring(k)) end
    table.insert(list("env"), k)
end
function hl.on(event, fn)
    if event ~= "hyprland.start" then err("unexpected event " .. event) end
    fn()
end
function hl.exec_cmd(cmd) table.insert(list("exec"), cmd) end
function hl.monitor(t)
    for k in pairs(t) do if not MONITOR[k] then err("unknown monitor field " .. k) end end
end
local curves = {}
function hl.curve(name, t) curves[name] = true end
function hl.animation(t)
    local c = t.bezier or t.spring or t.curve
    if c and not curves[c] and c ~= "default" then err("animation " .. tostring(t.leaf) .. " uses undefined curve " .. c) end
end
local function rule(kind, effects, t)
    if type(t.match) ~= "table" then err(kind .. " without a match table") ; return end
    for k in pairs(t.match) do if not MATCH[k] then err(kind .. ": unknown match property " .. k) end end
    for k in pairs(t) do
        if k ~= "name" and k ~= "enabled" and k ~= "match" and not effects[k] then
            err(kind .. ": unknown effect " .. k)
        end
    end
    table.insert(list(kind), t.match.class or t.match.namespace or "?")
end
function hl.window_rule(t) rule("window_rule", WEFF, t) end
function hl.layer_rule(t) rule("layer_rule", LEFF, t) end
function hl.bind(keys, d, opts)
    if type(d) ~= "table" or not d.__dsp then err("bind " .. tostring(keys) .. " has no dispatcher") end
    for k in pairs(opts or {}) do if not BINDOPT[k] then err("bind " .. keys .. ": unknown option " .. k) end end
    local cmd = d and d.__dsp == "exec_cmd" and d.args[1] or (d and d.__dsp) or "?"
    table.insert(list("binds"), { keys = keys, dsp = d and d.__dsp, cmd = cmd, opts = opts or {} })
end
hl.notification = { create = function(t) table.insert(list("notifications"), t.text) end }
return rec
"""


def lua_set(rt, names):
    t = rt.table()
    for n in names:
        t[n] = True
    return t


def run(confdir):
    rt = LuaRuntime(unpack_returned_tuples=True)
    g = rt.globals()
    g.DISPATCHERS = lua_set(rt, DISPATCHERS)
    g.OPTIONS = lua_set(rt, OPTIONS)
    g.MONITOR = lua_set(rt, API["monitor_fields"])
    g.MATCH = lua_set(rt, API["match_props"])
    g.WEFF = lua_set(rt, API["window_rule_effects"])
    g.LEFF = lua_set(rt, API["layer_rule_effects"])
    g.BINDOPT = lua_set(rt, API["bind_options"])
    rec = rt.execute(MOCK)
    # Hyprland puts the config's own directory first on package.path.
    rt.execute('package.path = %s .. "/?.lua;" .. package.path' % json.dumps(confdir.replace("\\", "/")))
    rt.execute(open(LUA, encoding="utf-8").read())

    def py(name):
        t = rec[name]
        return [] if t is None else [t[i] for i in range(1, len(t) + 1)]
    binds = [{"keys": b["keys"], "dsp": b["dsp"], "cmd": b["cmd"],
              "opts": dict(b["opts"].items())} for b in py("binds")]
    return {"errors": py("errors"), "exec": py("exec"), "binds": binds, "env": py("env"),
            "window_rule": py("window_rule"), "notifications": py("notifications"),
            "options": py("options")}


def norm_keys(s):
    # hyprlang writes modifiers space-separated ("SUPER SHIFT"), Lua joins
    # everything with "+" ("SUPER + SHIFT + R"); both become a sorted set.
    return " + ".join(sorted(p.upper() for p in re.split(r"[\s+,]+", s) if p))


def conf_facts():
    text = open(CONF, encoding="utf-8").read()
    mods = {"$mod": "SUPER"}
    binds, execs, rules, env = [], [], [], []
    for raw in text.splitlines():
        line = raw.split(" #", 1)[0].strip() if not raw.lstrip().startswith("exec") else raw.strip()
        if not line or line.startswith("#"):
            continue
        m = re.match(r"bind[a-z]*\s*=\s*([^,]*),\s*([^,]+),\s*([a-z]+),?\s*(.*)$", line)
        if m:
            mod = m.group(1).strip()
            for k, v in mods.items():
                mod = mod.replace(k, v)
            key = (mod + " + " + m.group(2).strip()) if mod else m.group(2).strip()
            binds.append(norm_keys(key))
            continue
        m = re.match(r"exec-once\s*=\s*(.*)$", line)
        if m:
            cmd = re.sub(r"\s+#.*$", "", m.group(1)).strip()
            execs.append(cmd)
            continue
        m = re.match(r"windowrule\s*=\s*match:class\s+(\S+),", line)
        if m:
            rules.append(m.group(1))
        m = re.match(r"env\s*=\s*([A-Z_]+),", line)
        if m:
            env.append(m.group(1))
    return binds, execs, rules, env


tmp = tempfile.mkdtemp(prefix="genesi-hypr-lua-")
try:
    print("== the shipped hyprland.lua against Hyprland's own API (%s)" % API["source"].split(" (")[0])
    facts = run(tmp)
    check(not facts["errors"], "every option, dispatcher, bind flag, rule and monitor field exists", facts["errors"])
    check(not facts["notifications"], "with no drop-ins present nothing is reported", facts["notifications"])
    check(any("genesi-bar shell --start" in e for e in facts["exec"]), "the bar starts at login")
    check(len(facts["options"]) >= 15, "the look & feel options are set (%d)" % len(facts["options"]))
    check("input:kb_layout" in facts["options"], "the keyboard layout is set")

    print("== hyprland.lua and hyprland.conf are the same desktop")
    cbinds, cexecs, crules, cenv = conf_facts()
    lbinds = [norm_keys(b["keys"]) for b in facts["binds"]]
    check(sorted(lbinds) == sorted(cbinds), "the same %d keys are bound" % len(cbinds),
          {"only in .conf": sorted(set(cbinds) - set(lbinds)), "only in .lua": sorted(set(lbinds) - set(cbinds))})
    check(len(lbinds) == len(set(lbinds)), "no key is bound twice in the .lua")
    check(sorted(facts["exec"]) == sorted(cexecs), "the same %d programs start at login" % len(cexecs),
          {"only in .conf": sorted(set(cexecs) - set(facts["exec"])), "only in .lua": sorted(set(facts["exec"]) - set(cexecs))})
    check(sorted(r.replace("\\\\", "\\") for r in facts["window_rule"]) == sorted(crules),
          "the same windows are ruled", (facts["window_rule"], crules))
    check(sorted(facts["env"]) == sorted(cenv), "the same environment is set", (facts["env"], cenv))
    launcher = [b for b in facts["binds"] if norm_keys(b["keys"]) == norm_keys("SUPER + SUPER_L")]
    check(launcher and launcher[0]["opts"].get("release") is True,
          "tapping SUPER alone opens the launcher on RELEASE (not on every SUPER combo)")
    mouse = [b for b in facts["binds"] if "MOUSE:" in norm_keys(b["keys"])]
    check(len(mouse) == 2 and all(b["opts"].get("mouse") for b in mouse), "window drag/resize are mouse binds")

    print("== drop-ins")
    with open(os.path.join(tmp, "genesi-display.lua"), "w", encoding="utf-8") as f:
        f.write("hl.monitor({ output = 'DP-1', scale = 1.25 })\n")
    with open(os.path.join(tmp, "user.lua"), "w", encoding="utf-8") as f:
        f.write("hl.bind('SUPER + F12', hl.dsp.exec_cmd('i-am-the-user'))\n")
    facts = run(tmp)
    check(not facts["errors"] and not facts["notifications"], "a valid drop-in and user.lua load quietly",
          facts["errors"] + facts["notifications"])
    check(facts["binds"][-1]["cmd"] == "i-am-the-user", "user.lua is loaded last, so the user wins")
    with open(os.path.join(tmp, "genesi-display.lua"), "w", encoding="utf-8") as f:
        f.write("this is not lua (\n")
    facts = run(tmp)
    check(any("genesi-display" in n for n in facts["notifications"]),
          "a BROKEN drop-in is reported on screen", facts["notifications"])
    check(any("genesi-bar shell --start" in e for e in facts["exec"]) and facts["binds"][-1]["cmd"] == "i-am-the-user",
          "...and the rest of the config, user.lua included, still loads")
finally:
    shutil.rmtree(tmp, ignore_errors=True)

# -- the migration -------------------------------------------------------------
#
# Writing hyprland.lua at the wrong moment costs people their config: on
# 0.55/0.56 Hyprland prefers it over a hyprland.conf that still works, so
# every edit in that .conf would silently stop applying. And a hyprland.lua
# the person wrote is theirs. Each case below is one of those mistakes.
import subprocess  # noqa: E402

MIGRATE = os.path.join(PKG, "genesi-hypr-lua-migrate")
SHIPPED_CONF = open(CONF, encoding="utf-8").read()
SHIPPED_LUA = open(LUA, encoding="utf-8").read()
AUTOGEN = "-- AUTOGENERATED HYPRLAND CONFIG.\nhl.config({ autogenerated = true })\n"


def home_with(conf=None, lua=None, user=None):
    h = tempfile.mkdtemp(prefix="genesi-hypr-home-")
    d = os.path.join(h, ".config", "hypr")
    os.makedirs(d)
    for name, text in (("hyprland.conf", conf), ("hyprland.lua", lua), ("user.lua", user)):
        if text is not None:
            with open(os.path.join(d, name), "w", encoding="utf-8", newline="\n") as f:
                f.write(text)
    return h


def migrate(h, version):
    r = subprocess.run([sys.executable, MIGRATE, "--home", h, "--force-version", version],
                       capture_output=True, text=True, encoding="utf-8", errors="replace",
                       env=dict(os.environ, GENESI_HYPR_SKEL=PKG))
    return r


def read(h, name):
    p = os.path.join(h, ".config", "hypr", name)
    return open(p, encoding="utf-8").read() if os.path.exists(p) else None


print("== the migration writes hyprland.lua only where Hyprland needs it")
homes = []
try:
    mine = SHIPPED_CONF + "\nbind = SUPER, T, exec, my-own-thing\nmonitor = DP-1, 2560x1440@144, 0x0, 1\n"
    for v in ("0.54.3", "0.55.0", "0.56.2"):
        h = home_with(conf=mine)
        homes.append(h)
        r = migrate(h, v)
        check(read(h, "hyprland.lua") is None and r.returncode == 0,
              "Hyprland %s: nothing written (it still reads hyprland.conf; 0.55/0.56 would PREFER a .lua and drop the user's edits)" % v,
              r.stdout + r.stderr)

    h = home_with(conf=mine)
    homes.append(h)
    r = migrate(h, "0.57.1-1.1")
    check(read(h, "hyprland.lua") == SHIPPED_LUA, "Hyprland 0.57 (the reported 0.57.1-1.1): Genesi's hyprland.lua is written",
          r.stdout + r.stderr)
    check(read(h, "hyprland.conf") == mine, "...and hyprland.conf is left exactly as it was")
    u = read(h, "user.lua") or ""
    check("-- bind = SUPER, T, exec, my-own-thing" in u and "-- monitor = DP-1" in u,
          "...and the user's OWN lines are listed in user.lua", u[-400:])
    listed = [l for l in u.split("\n\n", 1)[-1].splitlines() if l.strip()]
    check(len(listed) == 2 and "genesi-bar" not in u,
          "...only theirs: none of Genesi's own lines are listed as theirs", u[-600:])
    facts_ok = True
    try:
        from lupa import LuaRuntime as _LR
        _LR().execute(u)
    except Exception as e:  # noqa: BLE001
        facts_ok = str(e)
    check(facts_ok is True, "...and user.lua is valid Lua (every copied line is a comment)", facts_ok)

    r2 = migrate(h, "0.57.1")
    check(read(h, "hyprland.lua") == SHIPPED_LUA and read(h, "user.lua") == u, "running it again changes nothing")

    h = home_with(conf=SHIPPED_CONF)
    homes.append(h)
    migrate(h, "0.57.1")
    check(read(h, "user.lua") is None, "an untouched Genesi config gets no user.lua (there is nothing of theirs to list)")

    h = home_with(conf=SHIPPED_CONF, lua=AUTOGEN)
    homes.append(h)
    migrate(h, "0.57.1")
    check(read(h, "hyprland.lua") == SHIPPED_LUA, "Hyprland's autogenerated placeholder is replaced (the reported machine)")
    bak = os.path.join(h, ".config", "hypr", "hyprland.lua.autogenerated-bak")
    check(os.path.exists(bak) and open(bak, encoding="utf-8").read() == AUTOGEN, "...and kept as a backup")

    theirs = "-- my own config\nhl.bind('SUPER + T', hl.dsp.exec_cmd('foot'))\n"
    h = home_with(conf=SHIPPED_CONF, lua=theirs)
    homes.append(h)
    migrate(h, "0.57.1")
    check(read(h, "hyprland.lua") == theirs, "a hyprland.lua the user wrote is NEVER replaced")

    h = home_with(conf=mine, user="-- mine already\n")
    homes.append(h)
    migrate(h, "0.57.1")
    check(read(h, "user.lua") == "-- mine already\n", "an existing user.lua is never overwritten")

    other = "monitor = , preferred, auto, 1\nexec-once = waybar\nbind = SUPER, Return, exec, kitty\n"
    h = home_with(conf=other)
    homes.append(h)
    migrate(h, "0.57.1")
    check(read(h, "hyprland.lua") is None, "a Hyprland config that is not Genesi's is left alone")
finally:
    for h in homes:
        shutil.rmtree(h, ignore_errors=True)

print("== the pacman hook and the package")
hook = open(os.path.join(PKG, "genesi-hyprland-lua.hook"), encoding="utf-8").read()
check("Target = hyprland" in hook and "Operation = Upgrade" in hook and "When = PostTransaction" in hook
      and "/usr/lib/genesi/genesi-hypr-lua-migrate" in hook,
      "a pacman hook runs the migration when hyprland itself is upgraded")
pkgb = open(os.path.join(PKG, "PKGBUILD"), encoding="utf-8").read()
for path in ("/etc/skel/.config/hypr/hyprland.lua", "/usr/lib/genesi/genesi-hypr-lua-migrate",
             "/usr/share/libalpm/hooks/genesi-hyprland-lua.hook", "/usr/bin/genesi-hypr"):
    check(path in pkgb, "the package installs " + path)
inst = open(os.path.join(PKG, "genesi-caelestia-settings.install"), encoding="utf-8").read()
check(inst.count("_migrate_lua\n") >= 2, "the package's upgrade AND install run the migration")
shellj = json.load(open(os.path.join(PKG, "shell.json"), encoding="utf-8"))
logout = shellj["session"]["commands"]["logout"]
check(logout == ["genesi-hypr", "exit"], "Logout works on every Hyprland version (genesi-hypr exit)", logout)
gh = open(os.path.join(PKG, "genesi-hypr"), encoding="utf-8").read()
check("hl.dsp.exit()" in gh and "dispatch exit" in gh, "genesi-hypr exit tries the Lua form, then the old one")

# -- nothing else still speaks only the old hyprctl ----------------------------
#
# 0.57 removed `hyprctl keyword` and made `hyprctl dispatch` take Lua. A call
# in either old form is now an error that hyprctl answers with exit status 0,
# so the feature behind it just stops, silently. Every file that still uses an
# old form must also have the Lua one (`hyprctl eval`, `hl.dsp.`, usingLua)
# right there, choosing between them.
#
# PENDING lists files not ported yet, by name, so the gap is written down
# instead of being found by a user -- and a file leaving the list is the only
# way it can shrink: a listed file that no longer needs listing fails too.
PENDING = {
    "genesi-center/genesi-center-set": "Genesi Center's settings: keyword + a hyprlang drop-in",
    "genesi-display/genesi-display": "display scale/rotation: keyword monitor + a hyprlang drop-in",
    "genesi-input/genesi-input": "pointer speed: keyword input:* + a hyprlang drop-in",
}
LEGACY = re.compile(r"""["']hyprctl["'],\s*["'](keyword|dispatch)["']|hyprctl\s+(keyword|dispatch)\s+[a-z]|hypr\(\s*["']keyword["']|Hyprland\.dispatch\(\s*["'][a-z]""")
MODERN = re.compile(r"""["']eval["']|hyprctl eval|hl\.dsp\.|usingLua|genesi-hypr""")
COMMENT = re.compile(r"^\s*(#|//|\*|/\*|--)")
PKGS = os.path.join(HERE, "..", "packages")
print("== nothing speaks only the hyprctl that 0.57 removed")
legacy_only, pending_seen = [], set()
for root, dirs, files in os.walk(PKGS):
    dirs[:] = [d for d in dirs if d not in ("__pycache__", ".git", "node_modules")]
    for name in files:
        if not (name.endswith((".py", ".qml", ".sh")) or "." not in name or name == "PKGBUILD"):
            continue
        path = os.path.join(root, name)
        rel = os.path.relpath(path, PKGS).replace(os.sep, "/")
        try:
            text = open(path, encoding="utf-8").read()
        except (UnicodeDecodeError, OSError):
            continue
        code = "\n".join(l for l in text.splitlines() if not COMMENT.match(l))
        if not LEGACY.search(code):
            continue
        if rel in PENDING:
            pending_seen.add(rel)
        elif not MODERN.search(code):
            legacy_only.append(rel)
check(not legacy_only, "every hyprctl keyword/dispatch call has its Lua form beside it", legacy_only)
# The file-level check above only sees that a file KNOWS the Lua form, not
# that it acts on the answer. hyprshade is where that already went wrong once
# (our patch turned upstream's working Lua call into `keyword`), so its patch
# is held to the exact shape: Lua first, and stop there when it says "ok".
hs = open(os.path.join(PKGS, "genesi-hyprshade", "PKGBUILD"), encoding="utf-8").read()
check(re.search(r'"eval",.*?if lua\.stdout\.strip\(\) == "ok":\s*\n\s*return\s*\n.*?"keyword"', hs, re.S) is not None,
      "hyprshade sets the shader in Lua first and uses `keyword` only when Lua was refused")
for rel, why in PENDING.items():
    check(rel in pending_seen, "PENDING still needs listing: %s (%s)" % (rel, why),
          "it no longer uses the old forms -- take it off PENDING")
print("  note %d tool(s) still write hyprlang settings Hyprland 0.57 ignores: %s"
      % (len(PENDING), ", ".join(sorted(PENDING))))

print()
if failures:
    print("%d check(s) failed" % len(failures))
    sys.exit(1)
print("all checks passed")
